#!/usr/bin/env python3
"""Build the technical report's results table from the gallery workspaces.

Reads only committed workspace files (plan.json, reviews/*/review.json, runs/,
replication.json, log.jsonl) and gallery/scoreboard.json. Writes results_table.tex
next to this script. Rerun after any gallery change:

    python3 docs/launch/report/stats.py
"""
import glob
import json
import os
from datetime import datetime

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
GATES = ("question", "design", "results", "submission")


def parse(t):
    return datetime.strptime(t, "%Y-%m-%dT%H:%M:%SZ")


def workspace_row(ws, score):
    plan = json.load(open(os.path.join(ws, "plan.json")))
    gates = plan.get("gates", {})
    approved = sum(1 for g in GATES if gates.get(g, {}).get("status") == "approved")
    accepted = sum(len(gates.get(g, {}).get("accepted_findings") or []) for g in GATES)
    sev = {"critical": 0, "major": 0, "minor": 0}
    rounds = 0
    for path in glob.glob(os.path.join(ws, "reviews", "*", "review.json")):
        rounds += 1
        for f in json.load(open(path)).get("findings", []):
            sev[f["severity"]] = sev.get(f["severity"], 0) + 1
    runs = [d for d in glob.glob(os.path.join(ws, "runs", "*", "run.json"))]
    rerun = "--"
    rep = os.path.join(ws, "replication.json")
    if os.path.exists(rep):
        rerun = "pass" if json.load(open(rep)).get("passed") else "fail"
    times = []
    with open(os.path.join(ws, "log.jsonl")) as fh:
        for line in fh:
            line = line.strip()
            if line:
                times.append(parse(json.loads(line)["time"]))
    sub = gates.get("submission", {})
    end = parse(sub["decided_on"]) if sub.get("status") == "approved" else None
    hours = f"{(end - min(times)).total_seconds() / 3600:.1f}" if end else "--"
    answer = (score or {}).get("answer", {}).get("status", "--")
    return {
        "seed": os.path.basename(ws),
        "track": "CS" if plan_track(score) == "cs" else "SS",
        "gates": f"{approved}/4",
        "rounds": rounds,
        "sev": sev,
        "accepted": accepted,
        "runs": len(runs),
        "rerun": rerun,
        "answer": answer,
        "hours": hours,
    }


def plan_track(score):
    return (score or {}).get("track", "")


def main():
    board = json.load(open(os.path.join(ROOT, "gallery", "scoreboard.json")))
    scores = {r["workspace"]: r for r in board["results"]}
    rows = []
    for plan in sorted(glob.glob(os.path.join(ROOT, "gallery", "*", "plan.json"))):
        ws = os.path.dirname(plan)
        rel = os.path.relpath(ws, ROOT)
        rows.append(workspace_row(ws, scores.get(rel)))
    lines = [
        "% Generated by docs/launch/report/stats.py from gallery/; do not edit by hand.",
        "\\begin{tabular}{llcrrrrrcll}",
        "\\toprule",
        "Seed & Track & Gates & Reviews & Crit. & Major & Minor & Overruled & Runs & Rerun & Key \\\\",
        "\\midrule",
    ]
    for r in rows:
        s = r["sev"]
        lines.append(
            f"\\texttt{{{r['seed']}}} & {r['track']} & {r['gates']} & {r['rounds']} & "
            f"{s['critical']} & {s['major']} & {s['minor']} & {r['accepted']} & {r['runs']} & "
            f"{r['rerun']} & {r['answer']} \\\\"
        )
    tot = {k: sum(r["sev"][k] for r in rows) for k in ("critical", "major", "minor")}
    lines += [
        "\\midrule",
        f"Total & & & {sum(r['rounds'] for r in rows)} & {tot['critical']} & {tot['major']} & "
        f"{tot['minor']} & {sum(r['accepted'] for r in rows)} & {sum(r['runs'] for r in rows)} & & \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "",
    ]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results_table.tex")
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    for r in rows:
        print(r["seed"], r["gates"], r["rounds"], r["sev"], r["accepted"], r["runs"], r["rerun"],
              r["answer"], r["hours"] + "h")
    print("wrote", os.path.relpath(out, ROOT))


if __name__ == "__main__":
    main()
