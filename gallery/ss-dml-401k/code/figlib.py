"""Shared helpers for the figure and table scripts (code/fig_*.py, code/tab_*.py).

Rules (crew/agents/figures-ra.md): every number comes from a file a logged run wrote under
runs/, declared with --input; nothing is typed by hand and nothing new is estimated.

Macros. A table cell that the paper also quotes is written as the claim's macro from
paper/numbers.tex. The scripts do not read claims.jsonl (it is not a run output, and any
later claim edit would invalidate the run); they name the macro by the claims' fixed
convention `<Quantity><Learner><Two|Five>` for the (run, metric) pair they read, and list
every macro they used with its (run, metric) source as comments at the end of the fragment.
A separate check against claims.jsonl (CAPTIONS.md, "Macro check") confirms that each listed
macro's claim is backed by exactly that (run, metric).
"""
from __future__ import annotations

import json
import math
from pathlib import Path

LEARNERS = ["lasso", "tree", "forest", "boosting", "nnet"]
FOLDS = (2, 5)
NAME = {"lasso": "Lasso", "tree": "Regression tree", "forest": "Random forest",
        "boosting": "Boosted trees", "nnet": "Neural network"}
MACRO_LEARNER = {"lasso": "Lasso", "tree": "Tree", "forest": "Forest", "boosting": "Boosting",
                 "nnet": "Nnet"}
MACRO_K = {2: "Two", 5: "Five"}

