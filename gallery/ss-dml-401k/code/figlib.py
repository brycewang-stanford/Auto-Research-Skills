def load_json(path: str) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def load_metrics(run_id: str) -> dict:
    """Metrics file a logged run wrote (runs/<id>/metrics.json)."""
    return load_json(f"runs/{run_id}/metrics.json")


def write_metrics(path: str, metrics: dict) -> None:
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps(metrics, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def cell_key(learner: str, k: int) -> str:
    return f"{learner}_k{k}"


def macro_name(quantity: str, learner: str, k: int | None = None) -> str:
    return quantity + MACRO_LEARNER[learner] + ("" if k is None else MACRO_K[k])


class Macros:
    """Write a number as a claim macro and remember where it came from."""

    def __init__(self) -> None:
        self.sources: dict[str, str] = {}
        self.direct = 0

    def use(self, macro: str, run: str, metric: str, value) -> str:
        if not finite(value):
            raise ValueError(f"{run}:{metric} is not a finite number: {value!r}")
        src = f"{run}:{metric}"
        if self.sources.setdefault(macro, src) != src:
            raise AssertionError(f"macro {macro} used for {self.sources[macro]} and {src}")
        return "\\" + macro

    def raw(self, value, fmt: str) -> str:
        """A number no claim quotes, formatted from the run's metric."""
        if not finite(value):
            raise ValueError(f"not a finite number: {value!r}")
        self.direct += 1
        return format(value, fmt)

    def footer(self) -> list[str]:
        lines = ["% Macros used (macro = run:metric of the claim's first support):"]
        lines += [f"%   \\{m} = {s}" for m, s in sorted(self.sources.items())]
        return lines


def write_tex(path: str, source: str, body: list[str], footer: list[str]) -> None:
    """Write a LaTeX fragment (a bare tabular; the Writer adds the float and caption)."""
    head = [f"% Generated by {source} from logged runs. Do not edit by hand; rerun the script.",
            "% Needs \\usepackage{booktabs,icomma} and \\input{numbers.tex} for the macros",
            "% (icomma keeps the thousands comma in math mode, e.g. $7,701$, without a space)."]
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(head + body + footer) + "\n", encoding="utf-8")


def finite(*xs) -> bool:
    return all(isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)
               for x in xs)


def money(x: float) -> str:
    """Dollar label for figures, rounded as the claims' ',.0f' macros are; true minus sign."""
    s = format(x, ",.0f")
    if s == "-0":
        s = "0"
    return s.replace("-", "−")


