"""Shared helpers for the figure and table scripts (code/fig_*.py, code/tab_*.py).

Rules (crew/agents/figures-ra.md and the Figures RA brief): every number comes from a file
a logged run wrote, declared with --input; nothing reads claims.jsonl or data/raw; nothing
here computes a new result. Table cells the paper quotes are written as the claims' macro
names (paper/numbers.tex), and the metric value behind each macro is written next to it as
a LaTeX comment so the cell can be traced to its run.
"""
from __future__ import annotations

import json
from pathlib import Path

# One palette for every figure (Okabe-Ito, separable under colour-vision deficiency).
# Every encoding that matters also has a grayscale cue (position, marker fill, hatching,
# line style), so the figures read in print.
INK = "#222222"
MUTED = "#8a8a8a"
LIGHT = "#d9d9d9"
BLUE = "#0072B2"
VERMILLION = "#D55E00"
GREEN = "#009E73"
ORANGE = "#E69F00"
SKY = "#56B4E9"


def load_json(path: str) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def load_metrics(run_id: str) -> dict:
    """Metrics file a logged run wrote (runs/<id>/metrics.json)."""
    return load_json(f"runs/{run_id}/metrics.json")


def write_metrics(path: str, metrics: dict) -> None:
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps(metrics, indent=2, sort_keys=True) + "\n", encoding="utf-8")


